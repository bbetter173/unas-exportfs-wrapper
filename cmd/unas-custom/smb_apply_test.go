func TestSmbApply_GeneratesFile(t *testing.T) {
	dir := t.TempDir()
	cfgPath := filepath.Join(dir, "config.yaml")
	outPath := filepath.Join(dir, "smb-overrides.conf")

	cfg := `smb:
  overrides:
    - share: "Media"
      directives:
        guest ok: "yes"`
	if err := os.WriteFile(cfgPath, []byte(cfg), 0644); err != nil {
		t.Fatalf("failed to write config: %v", err)
	}

	result := runSmbApplyWithPaths(nil, cfgPath, outPath)
	if result != 0 {
		t.Fatalf("expected exit 0, got %d", result)
	}

	if _, err := os.Stat(outPath); err != nil {
		t.Fatalf("expected output file to exist: %v", err)
	}

	content, err := os.ReadFile(outPath)
	if err != nil {
		t.Fatalf("failed to read output file: %v", err)
	}
	if !strings.Contains(string(content), "[Media]") {
		t.Errorf("expected [Media] in output, got:\n%s", content)
	}
}

