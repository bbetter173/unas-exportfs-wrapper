func TestSmbApply_FileContent(t *testing.T) {
	dir := t.TempDir()
	cfgPath := filepath.Join(dir, "config.yaml")
	outPath := filepath.Join(dir, "smb-overrides.conf")

	cfg := `smb:
  overrides:
    - share: "Documents"
      directives:
        read only: "no"
        valid users: "@wheel"`
	if err := os.WriteFile(cfgPath, []byte(cfg), 0644); err != nil {
		t.Fatalf("failed to write config: %v", err)
	}

	result := runSmbApplyWithPaths(nil, cfgPath, outPath)
	if result != 0 {
		t.Fatalf("expected exit 0, got %d", result)
	}

	content, err := os.ReadFile(outPath)
	if err != nil {
		t.Fatalf("failed to read output file: %v", err)
	}
	s := string(content)

	if !strings.Contains(s, "[Documents]") {
		t.Errorf("expected [Documents] section in output, got:\n%s", s)
	}
	if !strings.Contains(s, "read only = no") {
		t.Errorf("expected 'read only = no' directive in output, got:\n%s", s)
	}
	if !strings.Contains(s, "valid users = @wheel") {
		t.Errorf("expected 'valid users = @wheel' directive in output, got:\n%s", s)
	}
	if !strings.Contains(s, "# Generated by unas-custom") {
		t.Errorf("expected header comment in output, got:\n%s", s)
	}
}

